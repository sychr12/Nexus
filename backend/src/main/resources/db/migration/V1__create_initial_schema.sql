CREATE TABLE IF NOT EXISTS memorandos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(255),
    descricao VARCHAR(255),
    unloc VARCHAR(255),
    municipio VARCHAR(255),
    memo_entrada VARCHAR(255),
    data_emissao DATE,
    quantidade INTEGER,
    usuario VARCHAR(255),
    criado_em TIMESTAMP,
    arquivo_word BYTEA
);

CREATE TABLE IF NOT EXISTS fluxo_processos (
    id VARCHAR(40) PRIMARY KEY,
    produtor VARCHAR(180) NOT NULL,
    cpf VARCHAR(14) NOT NULL,
    tipo_processo VARCHAR(30) NOT NULL,
    unidade_local VARCHAR(120) NOT NULL,
    tecnico_responsavel VARCHAR(120) NOT NULL,
    situacao VARCHAR(40) NOT NULL,
    formulario VARCHAR(255),
    fac VARCHAR(255),
    declaracao_produtor VARCHAR(255),
    declaracoes VARCHAR(255),
    documentos_gerados_json TEXT,
    fac_status VARCHAR(40),
    fac_gerada_em TIMESTAMP,
    fac_gerada_por VARCHAR(255),
    fac_impressa_em TIMESTAMP,
    fac_impressa_por VARCHAR(255),
    fac_assinada_anexada_em TIMESTAMP,
    fac_assinada_anexada_por VARCHAR(255),
    fac_assinada_documento_id VARCHAR(255),
    fac_rejeitada_motivo TEXT,
    memorando_arquivo VARCHAR(255),
    memorando_criado_em TIMESTAMP,
    memorando_quantidade INTEGER,
    memorando_produtores_json TEXT,
    memorandos_json TEXT,
    memorando_numero VARCHAR(255),
    memorando_lote_id VARCHAR(255),
    gerente_responsavel VARCHAR(255),
    gerente_assinado_em TIMESTAMP,
    assinatura_eletronica_json TEXT,
    encaminhado_gerente_em TIMESTAMP,
    enviado_analise_em TIMESTAMP,
    analista_responsavel VARCHAR(255),
    analisado_em TIMESTAMP,
    lancado_por VARCHAR(255),
    lancado_em TIMESTAMP,
    ultima_justificativa TEXT,
    criado_em TIMESTAMP,
    atualizado_em TIMESTAMP
);

CREATE TABLE IF NOT EXISTS fluxo_documentos (
    id VARCHAR(40) PRIMARY KEY,
    processo_id VARCHAR(40) NOT NULL,
    nome VARCHAR(160) NOT NULL,
    arquivo VARCHAR(240) NOT NULL,
    obrigatorio BOOLEAN,
    categoria VARCHAR(40) NOT NULL,
    mime_type VARCHAR(255),
    tamanho BIGINT,
    conteudo TEXT,
    criado_em TIMESTAMP,
    CONSTRAINT fk_fluxo_documentos_processo FOREIGN KEY (processo_id) REFERENCES fluxo_processos (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS fluxo_historico (
    id VARCHAR(40) PRIMARY KEY,
    processo_id VARCHAR(40) NOT NULL,
    usuario VARCHAR(120) NOT NULL,
    acao VARCHAR(180) NOT NULL,
    data_hora TIMESTAMP,
    observacao TEXT,
    CONSTRAINT fk_fluxo_historico_processo FOREIGN KEY (processo_id) REFERENCES fluxo_processos (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS fluxo_gerentes_unidade (
    id VARCHAR(40) PRIMARY KEY,
    nome VARCHAR(160) NOT NULL,
    unidade_local VARCHAR(120) NOT NULL,
    cargo VARCHAR(120) NOT NULL,
    telefone_corporativo VARCHAR(255),
    telefone_pessoal VARCHAR(255),
    status VARCHAR(30) NOT NULL,
    cadastrado_em TIMESTAMP,
    encerrado_em TIMESTAMP,
    atualizado_em TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_mensagens_destinatario_criado_em
    ON mensagens (destinatario_id, criado_em);
CREATE INDEX IF NOT EXISTS idx_mensagens_remetente_criado_em
    ON mensagens (remetente_id, criado_em);
CREATE INDEX IF NOT EXISTS idx_fluxo_processos_situacao
    ON fluxo_processos (situacao);
CREATE INDEX IF NOT EXISTS idx_fluxo_processos_cpf
    ON fluxo_processos (cpf);
CREATE INDEX IF NOT EXISTS idx_fluxo_documentos_processo
    ON fluxo_documentos (processo_id);
CREATE INDEX IF NOT EXISTS idx_fluxo_historico_processo_data
    ON fluxo_historico (processo_id, data_hora);
CREATE INDEX IF NOT EXISTS idx_analise_processos_analise
    ON analise_processos (analise_id);
